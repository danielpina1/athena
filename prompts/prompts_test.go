func TestRouterPrompt(t *testing.T) {
	for _, file := range []string{router, admission, replies, subscriptions} {
		if !strings.HasPrefix(file, "<!-- Adapted from deepseek-ai/dsh-superagent-prototype (MIT). -->\n") {
			t.Errorf("prompt file lacks the MIT header: %.60q", file)
		}
	}
	if strings.Contains(Router, "<!--") {
		t.Error("the composed prompt keeps a comment")
	}
	for _, banned := range []string{"orchestrator_", "Feishu", "feishu", "Harness", "DSH", "dsh-", "bash", "worktree_name"} {
		if strings.Contains(Router, banned) {
			t.Errorf("router prompt mentions %q", banned)
		}
	}
	for _, tool := range []string{"route", "eval_decide", "eval_read", "read", "reply", "request_status", "ticket_retry",
		"trigger_requeue", "thread_unsubscribe", "note"} {
		if !strings.Contains(Router, tool) {
			t.Errorf("router prompt never names %s", tool)
		}
	}
	if !strings.Contains(Router, "Never wait or poll") {
		t.Error("router prompt does not forbid polling")
	}
}

func TestWorkerPrompt(t *testing.T) {
	for _, banned := range []string{"orchestrator_", "Feishu", "feishu", "DSH_", "lark-cli", "reply_to_trigger_id", "pr_number",
		"purpose `answer`", "purpose `result`"} {
		if strings.Contains(Worker, banned) {
			t.Errorf("worker prompt mentions %q", banned)
		}
	}
	for _, want := range []string{"`report`", "`ack`", "`reply`", "`follow_thread`", "`mark_unrelated`", "`handback`", "`pull`",
		"athena/<ticket id>", "git push -u origin", "gh pr create", "ATHENA_GITHUB_REPOSITORY", "ATHENA_GITHUB_ACCOUNT",
		"ATHENA_GITHUB_COMMIT_EMAIL", "ATHENA_GITHUB_NUMBER", "ATHENA_GITHUB_PR_HEAD", "trigger_id", "600 characters",
		"Discover how the repository builds", "## Commits and pull requests", "pull_request_template", "No trailers",
		"`## Summary`", "`## Changes`", "`## Testing`", "`## Notes`", "Closes #N", "\"generated by\" line",
		"Never say how the work was produced", "Words that belong to the change itself are fine", "`Signed-off-by`",
		"never an attribution trailer", "`--no-verify`", "`--amend`", "never commit secrets", "ATHENA_GITHUB_KIND",
		"`message from the owner (not on GitHub)`", "acknowledge, hand back or answer only messages with a `trigger_id`",
		"## The order of your calls", "`acknowledged: no`", "`acknowledged: yes`", "Never send the result yourself",
		"is an input id and never a `trigger_id`", "a repeat `ack` posts nothing", "`reply` only answers",
		"a `ready` report never carries a `question`"} {
		if !strings.Contains(Worker, want) {
			t.Errorf("worker prompt lacks %q", want)
		}
	}
}

func TestPartsIncludeReviewer(t *testing.T) {
	parts := Parts()
	if last := parts[len(parts)-1]; last.Name != PartReviewer || last.Default != Reviewer {
		t.Fatalf("last part = %s, want the reviewer", last.Name)
	}
	if strings.Contains(Router, Reviewer) || strings.Contains(Worker, Reviewer) {
		t.Error("the reviewer prompt is part of another session's prompt")
	}
	// What to read, the closed output, the verdict rule, and no writes.
	for _, want := range []string{"git diff", "tests", "`review`", "verdict", "approved", "changes", "- none",
		"[high]", "[medium]", "[low]", "<file>:<line>", "high or medium", "Never edit", "commit", "push"} {
		if !strings.Contains(Reviewer, want) {
			t.Errorf("reviewer prompt lacks %q", want)
		}
	}
	for _, banned := range []string{"`report`", "orchestrator_", "nucleos"} {
		if strings.Contains(Reviewer, banned) {
			t.Errorf("reviewer prompt mentions %q", banned)
		}
	}
}

